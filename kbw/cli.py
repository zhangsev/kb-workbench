def cmd_doctor(args) -> int:
    rows: list[tuple[str, str, str, str]] = []  # (level, name, detail, fix)

    def add(ok, name, detail="", fix="", required=True):
        rows.append(("ok" if ok else ("FAIL" if required else "warn"), name, detail, "" if ok else fix))

    py = sys.version_info
    add(py >= (3, 11), "python >= 3.11", sys.version.split()[0], "install Python 3.11 and recreate .venv")
    setup_cmd = "python -m kbw setup"
    for mod, pkg, req in (("mcp", "mcp", True), ("yaml", "PyYAML", True), ("fastembed", "fastembed", False),
                          ("onnxruntime", "onnxruntime", False), ("sqlite_vec", "sqlite-vec", False)):
        try:
            __import__(mod)
            from importlib.metadata import version
            add(True, f"python package {pkg}", version(pkg))
        except Exception as exc:
            add(False, f"python package {pkg}", type(exc).__name__, setup_cmd, required=req)
    import sqlite3
    con = sqlite3.connect(":memory:")
    try:
        con.execute("CREATE VIRTUAL TABLE t USING fts5(a)")
        add(True, "sqlite FTS5", sqlite3.sqlite_version)
    except sqlite3.Error as exc:
        add(False, "sqlite FTS5", str(exc), "use a Python build whose SQLite includes FTS5 (python.org builds do)")
    add(hasattr(con, "enable_load_extension"), "sqlite extension loading", "",
        "use a Python build compiled with loadable-extension support (python.org builds; not some distro/pyenv builds)",
        required=False)

    node = resolve_command("node", [])
    if node:
        v = run([node[0], "--version"]).stdout.strip()
        major = int(v.lstrip("v").split(".")[0]) if v else 0
        add(20 <= major < 25, "node >= 20 and < 25", v, "install Node.js 22 LTS")
    else:
        add(False, "node >= 20 and < 25", "not found", "install Node.js 22 LTS")
    for tool, fix in (("git", "install git"), ("rg", setup_cmd)):
        r = find_rg() if tool == "rg" else resolve_command(tool, [])
        add(bool(r), tool, r[0] if r else "not found", fix, required=tool == "git")

    cfg = None
    try:
        from .config import load_config
        cfg = load_config(args.config)
        add(True, "config", str(cfg.file))
    except Exception as exc:
        add(False, "config", str(exc), "copy kbw.example.yaml to kbw.yaml and edit it (or `python -m kbw setup --examples`)")

    if cfg:
        spec = cfg.llmwiki_command()
        if spec and spec[0] == "node":
            add(Path(spec[1][0]).is_file(), "llmwiki-mcp (source build)", spec[1][0],
                setup_cmd + "  (offline: copy vendor/src/llmwiki including node_modules and dist)")
        elif spec:
            add(bool(resolve_command(spec[0], [])), "llmwiki-mcp (custom command)", spec[0], "fix downstream.llmwiki.command")
        cli = cfg.codegraph_cli()
        res = resolve_command(cli[0], cli[1])
        if res:
            try:
                ver = run([res[0], *res[1], "version"], env=downstream_env(), timeout=30).stdout.strip().splitlines()
                add(bool(ver), "codegraph", (ver or ["no version output"])[-1], setup_cmd)
            except Exception as exc:
                add(False, "codegraph", str(exc), setup_cmd)
        else:
            add(False, "codegraph", "not found", setup_cmd)
        root = cfg.wiki_root
        add(bool(root and (root / "wiki").is_dir()), "knowledge wiki_root", str(root),
            "set knowledge.wiki_root to a .wiki directory containing wiki/ and raw/")
        for d in cfg.source_dirs:
            add(d.is_dir(), "source dir", str(d), "create it or fix knowledge.source_dirs", required=False)
        if not cfg.source_dirs:
            add(False, "source dirs", "none configured: read_source is disabled", "set knowledge.source_dirs", required=False)
        try:
            from .gateway import Gateway
            gw = Gateway(cfg)
            add(True, "database", str(gw.store.path))
            add(gw.store.vec_ok, "sqlite-vec loads", gw.store.vec_error or "", setup_cmd, required=False)
            counts = gw.store.counts()
            add(counts["pages"] > 0, "knowledge index", json.dumps(counts), "python -m kbw index", required=False)
            add(gw.embedder.model_present(), f"embedding model {cfg.embedding_model}", str(cfg.model_dir),
                setup_cmd + "  (offline: copy the model directory into models.dir)", required=False)
            if cfg.rerank_enabled:
                add(gw.reranker.model_present(), f"reranker model {cfg.reranker_model}", str(cfg.model_dir), setup_cmd, required=False)
            for repo in cfg.repos:
                st = gw.code.repo_state(repo)
                add(st["exists"], f"repo {repo.name} path", st["path"], "fix repos[].path in kbw.yaml")
                if st["exists"]:
                    add(st["indexed"], f"repo {repo.name} index", st["freshness"], "python -m kbw index", required=False)
                    add(st["freshness"] in ("fresh", "uncommitted_changes"), f"repo {repo.name} freshness",
                        st["freshness"], "python -m kbw index", required=False)
                for dep in repo.depends_on:
                    add(cfg.repo(dep) is not None, f"repo {repo.name} depends_on {dep}", "",
                        "depends_on must name another configured repo", required=False)
            gw.store.close()
        except Exception as exc:
            add(False, "database", f"{type(exc).__name__}: {exc}", "check data_dir is writable")

    width = max(len(r[1]) for r in rows)
    for level, name, detail, fix in rows:
        print(f"[{level:>4}] {name:<{width}}  {detail}")
        if fix:
            print(f"{'':>7}fix: {fix}")
    fails = sum(r[0] == "FAIL" for r in rows)
    warns = sum(r[0] == "warn" for r in rows)
    print(f"\n{fails} failed, {warns} warnings (warnings mean a retrieval route is degraded, not broken)")
    return 1 if fails else 0


# ---------------------------------------------------------------- entry

def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="kbw", description=f"kb-workbench {__version__}")
    ap.add_argument("--config", help="path to kbw.yaml (default: ./kbw.yaml or $KBW_CONFIG)")
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("setup", help="install pinned dependencies, upstream programs and models (the only command that downloads)")
    s.add_argument("--offline", action="store_true", help="install from vendor/ only, never use the network")
    s.add_argument("--examples", action="store_true", help="create demo repos, demo knowledge and kbw.yaml")
    s.add_argument("--pack-offline", action="store_true", help="also download wheels into vendor/wheelhouse")
    s.set_defaults(fn=cmd_setup)
    s = sub.add_parser("index", help="build or update code indexes and the knowledge index")
    s.add_argument("--rebuild", action="store_true", help="rebuild code indexes from scratch")
    s.add_argument("--code-only", action="store_true")
    s.add_argument("--knowledge-only", action="store_true")
    s.add_argument("--repo", action="append", metavar="NAME",
                   help="index only this configured repo (repeatable); skips the knowledge index")
    s.set_defaults(fn=cmd_index)
    s = sub.add_parser("serve", help="run the MCP gateway on stdio")
    s.add_argument("--log-level", default="INFO")
    s.set_defaults(fn=cmd_serve)
    s = sub.add_parser("status", help="show index, model and gateway state")
    s.add_argument("--json", action="store_true")
    s.set_defaults(fn=cmd_status)
    s = sub.add_parser("query", help="run one search from the terminal (same code path as the MCP tools)")
    s.add_argument("kind", choices=["code", "knowledge", "all"])
    s.add_argument("text")
    s.add_argument("--repos", help="comma-separated repo names (code only)")
    s.add_argument("--top-k", type=int, default=8)
    s.add_argument("--json", action="store_true", help="print the full tool result")
    s.set_defaults(fn=cmd_query)
    sub.add_parser("stop", help="stop gateway processes started from this config").set_defaults(fn=cmd_stop)
    sub.add_parser("doctor", help="check runtime, upstream programs, indexes, models and database").set_defaults(fn=cmd_doctor)
    args = ap.parse_args(argv)
    if args.cmd != "serve":
        setup_logging("WARNING")
    try:
        return args.fn(args)
    except FileNotFoundError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
