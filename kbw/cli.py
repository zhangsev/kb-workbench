REQ_IN, REQ_LOCK = PROJECT_ROOT / "requirements.in", PROJECT_ROOT / "requirements.lock"
WHEELHOUSE, NPM_CACHE = PROJECT_ROOT / "vendor" / "wheelhouse", PROJECT_ROOT / "vendor" / "npm-cache"
NPM_PACKAGES = [f"@colbymchenry/codegraph@{UPSTREAM['codegraph']}"]


def _stream(cmd: list[str], cwd=None, env=None) -> int:
    print("  $ " + " ".join(cmd), flush=True)
    try:
        return subprocess.run(cmd, cwd=cwd, env=env, stdin=subprocess.DEVNULL).returncode
    except FileNotFoundError:
        print(f"  not found: {cmd[0]}")
        return 127


def _offline(args) -> bool:
    if getattr(args, "offline", False) or os.environ.get("KBW_OFFLINE") == "1":
        return True
    try:
        from .config import load_config
        return load_config(args.config).offline
    except Exception:
        return False


# ---------------------------------------------------------------- setup

def cmd_setup(args) -> int:
    offline = _offline(args)
    print(f"kbw setup ({'OFFLINE: local files only' if offline else 'online'})")
    failures = []

    print("\n[1/4] Python packages")
    req = REQ_LOCK if REQ_LOCK.exists() else REQ_IN
    pip = [sys.executable, "-m", "pip", "install", "--disable-pip-version-check", "-r", str(req)]
    if offline:
        if not WHEELHOUSE.is_dir():
            print(f"  missing {WHEELHOUSE}. Prepare it on a connected machine of the same OS and Python version:\n"
                  f"    python -m kbw setup --pack-offline")
            failures.append("python packages")
        else:
            pip += ["--no-index", "--find-links", str(WHEELHOUSE)]
    if "python packages" not in failures and _stream(pip) != 0:
        failures.append("python packages")
    elif not REQ_LOCK.exists() and not offline:
        frozen = run([sys.executable, "-m", "pip", "freeze", "--exclude-editable"], timeout=120).stdout
        REQ_LOCK.write_text("# Generated by `kbw setup` from requirements.in; commit this file.\n" + frozen,
                            encoding="utf-8")
        print(f"  wrote {REQ_LOCK.name}")
    # make `python -m kbw` importable from any directory without a build step
    import site
    for sp in site.getsitepackages():
        try:
            (Path(sp) / "kbw_project.pth").write_text(str(PROJECT_ROOT) + "\n", encoding="utf-8")
            break
        except OSError:
            continue

    print("\n[2/4] Upstream programs (pinned source, Node package, ripgrep)")
    from .install import setup_llmwiki, setup_rg
    npm = resolve_command("npm", [])
    node_dir = PROJECT_ROOT / "vendor" / "node"
    if not setup_llmwiki(offline, npm, _stream):
        failures.append("LLMWiki source build")
    if not setup_rg(offline):
        failures.append("ripgrep")
    if not npm:
        print("  npm not found. Install Node.js 20 or newer (22 LTS recommended), then re-run setup.")
        failures.append("node packages")
    else:
        node_dir.mkdir(parents=True, exist_ok=True)
        # A missing package must not block installation/verification of the other.
        for package in NPM_PACKAGES:
            cmd = [npm[0], *npm[1], "install", "--prefix", str(node_dir), "--no-audit", "--no-fund",
                   "--cache", str(NPM_CACHE), package]
            if offline:
                cmd.insert(len(npm[1]) + 2, "--offline")
            if _stream(cmd, env=downstream_env()) != 0:
                failures.append(f"node package {package}")

    if args.examples:
        from . import examples
        setup_logging()
        examples.create(PROJECT_ROOT, PROJECT_ROOT / "kbw.yaml")

    print("\n[3/4] Models")
    try:
        from .config import load_config
        from .embed import Embedder, Reranker
        cfg = load_config(args.config)
        todo = [Embedder(cfg.embedding_model, cfg.model_dir, offline)]
        if cfg.rerank_enabled:
            todo.append(Reranker(cfg.reranker_model, cfg.model_dir, offline, enabled=True))
        cfg.model_dir.mkdir(parents=True, exist_ok=True)
        for m in todo:
            if offline and not m.model_present():
                print(f"  {m.name}: not in {cfg.model_dir}. Copy the model directory from a connected machine.")
                failures.append(f"model {m.name}")
                continue
            m.load(allow_download=not offline)
            print(f"  {m.name}: {m.status['state']}" + (f" ({m.status['reason']})" if m.status["reason"] else ""))
            if m.status["state"] != "loaded":
                failures.append(f"model {m.name}")
    except FileNotFoundError as exc:
        print(f"  skipped: {exc}")

    if args.pack_offline:
        print("\n[pack] Downloading wheels for offline installs into vendor/wheelhouse")
        WHEELHOUSE.mkdir(parents=True, exist_ok=True)
        if _stream([sys.executable, "-m", "pip", "download", "-r", str(REQ_LOCK if REQ_LOCK.exists() else REQ_IN),
                    "-d", str(WHEELHOUSE)]) != 0:
            failures.append("wheelhouse")

    print("\n[4/4] Result")
    if failures:
        print("  FAILED: " + ", ".join(failures) + "\n  Run `python -m kbw doctor` for the exact fix commands.")
        return 1
    print("  OK. Next: `python -m kbw index`, then `python -m kbw doctor`.")
    return 0


# ---------------------------------------------------------------- index

def _exclude_codegraph(repo: Path) -> None:
    """Keep generated index metadata local without changing tracked .gitignore."""
    target = git(repo, "rev-parse", "--path-format=absolute", "--git-path", "info/exclude")
    if target:
        path = Path(target)
        existing = path.read_text(encoding="utf-8") if path.exists() else ""
        if "/.codegraph/" not in existing.splitlines():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(existing + ("\n" if existing and not existing.endswith("\n") else "")
                            + "/.codegraph/\n", encoding="utf-8")


def cmd_index(args) -> int:
    from .config import load_config
    from .embed import Embedder, Reranker
    from .gateway import Gateway

    cfg = load_config(args.config)
    cli = cfg.codegraph_cli()
    resolved = resolve_command(cli[0], cli[1])
    rc = 0
    gw = Gateway(cfg)
    try:
        version = None
        if resolved:
            version = (run([*resolved[0:1], *resolved[1], "version"], env=downstream_env()).stdout.strip()
                       .splitlines() or [None])[-1]
        wanted = list(args.repo or [])
        unknown = [w for w in wanted if not cfg.repo(w)]
        if unknown:
            print(f"unknown repos: {unknown}; configured: {[r.name for r in cfg.repos]}")
            return 2
        targets = [r for r in cfg.repos if not wanted or r.name in wanted]
        for repo in targets if not args.knowledge_only else []:
            print(f"\n[code] {repo.name}  {repo.path}")
            if not repo.path.is_dir():
                print("  path does not exist; skipped"); rc = 1; continue
            if not resolved:
                print("  codegraph not installed; skipped (run `python -m kbw setup`)"); rc = 1; continue
            indexed = any(repo.path.glob(".codegraph*/codegraph.db"))
            # Published npm builds have no --local-only, and their .gitignore
            # explicitly unignores itself. Use git's local exclude instead.
            _exclude_codegraph(repo.path)
            sub = ["sync", str(repo.path)] if indexed and not args.rebuild else (
                ["index", str(repo.path)] if indexed else ["init", str(repo.path), "--yes"])
            t0 = time.perf_counter()
            code = _stream([resolved[0], *resolved[1], *sub], env=downstream_env())
            print(f"  exit {code}, {time.perf_counter() - t0:.1f}s")
            if code == 0:
                gw.store.set_repo_index(repo.name, gw.code.repo_state(repo, True)["commit"], version)
            else:
                rc = 1
        if not args.code_only and not wanted:
            print("\n[knowledge]")
            if not cfg.wiki_pages_dir or not cfg.wiki_pages_dir.is_dir():
                print(f"  wiki pages directory not found: {cfg.wiki_pages_dir}"); rc = 1
            else:
                print("  " + json.dumps(gw.knowledge.sync(), ensure_ascii=False))
                if gw.embedder.status["reason"]:
                    print(f"  semantic index skipped: {gw.embedder.status['reason']}")
                if not gw.store.vec_ok:
                    print(f"  semantic index skipped: {gw.store.vec_error}")
    finally:
        gw.store.close()
    return rc


