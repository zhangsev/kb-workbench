# ---------------------------------------------------------------- status / stop

def _alive(pid: int) -> bool:
    if os.name == "nt":
        out = run(["tasklist", "/FI", f"PID eq {pid}", "/NH", "/FO", "CSV"]).stdout
        return f'"{pid}"' in out
    try:
        os.kill(pid, 0)
        return True
    except OSError:
        return False


def _is_gateway(pid: int) -> bool:
    """Guard against pid reuse: only a process whose command line is `kbw serve` qualifies."""
    try:
        if os.name == "nt":
            cmdline = run(["powershell", "-NoProfile", "-Command",
                           f"(Get-CimInstance Win32_Process -Filter 'ProcessId={pid}').CommandLine"]).stdout
        elif Path(f"/proc/{pid}/cmdline").exists():
            cmdline = Path(f"/proc/{pid}/cmdline").read_bytes().replace(b"\x00", b" ").decode(errors="replace")
        else:
            cmdline = run(["ps", "-p", str(pid), "-o", "command="]).stdout
    except (OSError, subprocess.SubprocessError):
        return False
    return "kbw" in cmdline and "serve" in cmdline


def _gateways(cfg) -> list[dict]:
    out = []
    for f in sorted((cfg.data_dir / "run").glob("*.json")):
        try:
            info = json.loads(f.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        info["file"] = f
        info["alive"] = _alive(info["pid"]) and _is_gateway(info["pid"])
        if not info["alive"]:
            f.unlink(missing_ok=True)  # stale record
            continue
        out.append(info)
    return out


def cmd_status(args) -> int:
    from .config import load_config
    from .gateway import Gateway

    cfg = load_config(args.config)
    gw = Gateway(cfg)
    try:
        import asyncio
        st = asyncio.run(gw.status())
    finally:
        gw.store.close()
    st["running_gateways"] = [{"pid": g["pid"], "started": g["started"]} for g in _gateways(cfg)]
    st["note"] = ("stdio mode: each MCP client owns one gateway process; downstream connection state is "
                  "per process, call the service_status tool from the client to see it")
    if args.json:
        print(json.dumps(st, ensure_ascii=False, indent=2, default=str))
        return 0
    print(f"config: {st['config']}   offline: {st['offline']}")
    print(f"knowledge: {st['knowledge']['pages']} pages, {st['knowledge']['chunks']} chunks, "
          f"semantic vectors: {st['knowledge']['vectors']}")
    cov = st["index_coverage"]
    print(f"code index coverage: {cov['indexed']}/{cov['configured']} repos indexed "
          "(unindexed repos are still searched by exact text and file name, without call graphs)")
    for r in st["repos"]:
        print(f"repo {r['repo']}: indexed={r['indexed']} freshness={r['freshness']} commit={(r['commit'] or '?')[:10]}")
    if cov["not_indexed"]:
        print("to index one repo: python -m kbw index --repo " + cov["not_indexed"][0])
    print(f"embedding model: {st['models']['embedding']['state']}  reranker: {st['models']['reranker']['state']}")
    print(f"running gateways: {[g['pid'] for g in st['running_gateways']] or 'none'}")
    return 0


def cmd_query(args) -> int:
    """One search without an MCP client: for checking routing and results by hand."""
    import asyncio

    from .config import load_config
    from .gateway import Gateway

    cfg = load_config(args.config)

    async def go() -> dict:
        gw = Gateway(cfg)
        try:
            if args.kind == "code":
                repos = [r.strip() for r in args.repos.split(",") if r.strip()] if args.repos else None
                return await gw.search_code(args.text, repos, args.top_k)
            if args.kind == "knowledge":
                return await gw.search_knowledge(args.text, args.top_k)
            return await gw.search_all(args.text, args.top_k)
        finally:
            await gw.close()

    res = asyncio.run(go())
    if args.json:
        print(json.dumps(res, ensure_ascii=False, indent=2, default=str))
        return 0
    if "terms" in res:
        print("terms:   " + (", ".join(f"{t['text']}({t['kind']})" for t in res["terms"]) or "(none)")
              + f"   [{res['term_mode']}]")
        for r in [r for r in res["routing"] if r["score"] > 0][:5]:
            print(f"route:   {r['repo']}  score={r['score']:g}  {'; '.join(r['why'])}")
        print("queried: " + (", ".join(f"{q['repo']}({q['sections']})" for q in res["repos_queried"]) or "(none)"))
        cov = res["index_coverage"]
        print(f"index:   {cov['indexed']}/{cov['configured']} repos indexed")
    for d in res.get("degraded", []):
        print("degraded: " + d)
    if res.get("hint"):
        print("hint:    " + res["hint"])
    print(f"results: {len(res['results'])}")
    for i, r in enumerate(res["results"], 1):
        where = r.get("page") or f"{r['repo']}:{r['path']}"
        lines = r.get("lines") or [None, None]
        print(f"\n{i}. {where}  lines {lines[0]}-{lines[1]}  via {','.join(r.get('route_ranks', {})) or r.get('kind', '')}")
        for line in (r.get("snippet") or "").splitlines()[:8]:
            print("     " + line[:160])
    print(f"\ncache hit: {res.get('cache', {}).get('hit')}   time: {res.get('cache', {}).get('ms')} ms")
    return 0


def cmd_stop(args) -> int:
    from .config import load_config

    cfg = load_config(args.config)
    gws = _gateways(cfg)
    if not gws:
        print("no running gateway")
        return 0
    for g in gws:
        pid = g["pid"]
        # Terminate only the gateway itself. Its downstream children exit when their
        # stdin closes; CodeGraph's shared daemon is left alone on purpose.
        if os.name == "nt":
            run(["taskkill", "/PID", str(pid), "/F"])
        else:
            os.kill(pid, signal.SIGTERM)
        for _ in range(50):
            if not _alive(pid):
                break
            time.sleep(0.1)
        print(f"gateway {pid}: {'stopped' if not _alive(pid) else 'still running'}")
        g["file"].unlink(missing_ok=True)
    return 0


